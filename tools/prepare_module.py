#!/usr/bin/env python3
"""Prepare a game DLL for lifting as a second guest module (server.dll).

  prepare_module.py <game.dll> <base> <outdir> <genout> <prefix>

Lifted code bakes absolute addresses into the generated C, so the DLL is
lifted as if it were loaded at the fixed guest base the runtime maps it at
(server.dll: 0x00A00000; its preferred base 0x10000000 is the guest heap).
The runtime maps the ORIGINAL file at that base and applies the file's own
base relocations, which gives the same bytes as the analysis copy written
here.  Outputs (all derived from the game binary, never committed):

  <outdir>/image.dll    the analysis copy, relocated to <base>
  <outdir>/relocs.txt   VAs of every HIGHLOW fixup slot (genall.py RELOCS)
  <outdir>/seeds.txt    entry point and exports (genall.py SEEDS)
  <outdir>/sha256.txt   SHA-256 of the original file
  <genout>/modinfo.c    the module's identity for the runtime loader

The original file is only read.
"""
import hashlib, os, sys
import pefile


def main(src, base, outdir, genout, prefix):
    raw = open(src, 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    pe = pefile.PE(data=raw)
    pref = pe.OPTIONAL_HEADER.ImageBase
    size = pe.OPTIONAL_HEADER.SizeOfImage
    if pe.FILE_HEADER.Machine != 0x14c or not pe.FILE_HEADER.Characteristics & 0x2000:
        sys.exit(f"{src}: not an i386 DLL")
    if not hasattr(pe, 'DIRECTORY_ENTRY_BASERELOC'):
        sys.exit(f"{src}: no base relocations, cannot be moved to {base:#x}")
    kinds = {e.type for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries}
    if kinds - {0, 3}:
        sys.exit(f"{src}: relocation types {sorted(kinds - {0, 3})} are not supported (only HIGHLOW)")
    slots = sorted(base + e.rva for b in pe.DIRECTORY_ENTRY_BASERELOC for e in b.entries if e.type == 3)
    pe.relocate_image(base)
    pe.OPTIONAL_HEADER.ImageBase = base
    os.makedirs(outdir, exist_ok=True)
    img = os.path.join(outdir, 'image.dll')
    pe.write(img)

    pe = pefile.PE(img)
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from lift import code_range                    # .text and the code sections right after it
    tlo, tsz, _ = code_range(pe)
    thi = tlo + tsz
    entry = base + pe.OPTIONAL_HEADER.AddressOfEntryPoint
    seeds = [entry]
    exports = []
    syms = pe.DIRECTORY_ENTRY_EXPORT.symbols if hasattr(pe, 'DIRECTORY_ENTRY_EXPORT') else []
    for e in syms:
        va = base + e.address
        exports.append(((e.name or b'').decode('latin1'), e.ordinal, va))
        if tlo <= va < thi:
            seeds.append(va)
    with open(os.path.join(outdir, 'relocs.txt'), 'w') as f:
        f.write('\n'.join(f'{a:08x}' for a in slots))
    with open(os.path.join(outdir, 'seeds.txt'), 'w') as f:
        f.write('\n'.join(f'{a:08x}' for a in sorted(set(seeds))))
    with open(os.path.join(outdir, 'sha256.txt'), 'w') as f:
        f.write(sha + '\n')

    name = os.path.basename(src).lower()
    os.makedirs(genout, exist_ok=True)
    with open(os.path.join(genout, 'modinfo.c'), 'w') as f:
        f.write('/* generated by tools/prepare_module.py: identity of the lifted module */\n')
        f.write('#include "module.h"\n')
        f.write(f'const ModInfo g_{prefix}modinfo = {{\n')
        f.write(f'  "{name}", "{sha}",\n')
        f.write(f'  0x{base:08x}u, 0x{pref:08x}u, 0x{size:08x}u, 0x{entry:08x}u,\n')
        f.write(f'  0x{tlo:08x}u, 0x{thi - tlo:08x}u, {len(raw)}u,\n')
        f.write('};\n')
    print(f"prepare_module: {src}: {len(raw)} bytes, sha256 {sha[:16]}..., base {pref:#x} -> {base:#x}, "
          f"size {size:#x}, .text {tlo:#x}-{thi:#x}, {len(slots)} fixups, exports "
          + ", ".join(f"{n or '#%d' % o}@{va:#x}" for n, o, va in exports))


if __name__ == '__main__':
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    main(sys.argv[1], int(sys.argv[2], 0), sys.argv[3], sys.argv[4], sys.argv[5])
